import json,subprocess
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
WORK=ROOT.parent.parent/'work/demo-v2-take2'
ASSETS=ROOT/'assets'
MUSIC=ROOT/'integration/tiktok/music/mdeditor-light-steps-v1.wav'
CAPTIONS=[
 (0,3,'mdEditor — WindowsでMarkdownを編集','mdEditor — Markdown on Windows'),
 (3,9,'「開く」から、図と数式のサンプルを選択','Open a sample with diagrams and math'),
 (9,13,'見出しを編集。プレビューも更新','Edit the heading. The preview updates.'),
 (13,17,'KaTeXで数式を表示','Preview the equation with KaTeX'),
 (17,23,'Mermaidの文字を変更。図にも反映','Edit a Mermaid label. The diagram updates.'),
 (23,25,'Markdownを保存','Save the Markdown document'),
 (25,33,'「書き方」（英語ではSyntax）で書式と表示例を確認','Syntax opens a Markdown reference with examples'),
 (33,35,'一覧を閉じて、編集画面へ','Close the reference and return to editing'),
 (35,46,'プレビューを別ウィンドウへ。編集画面と並べて確認','Open the preview in a separate window beside the editor'),
 (46,53,'ダークモードへ。別ウィンドウも切り替わる','Switch to dark mode. The separate preview follows.'),
 (53,56,'プレビューを本体に戻す','Return the preview to the main window'),
 (56,63,'「PDFに保存」で保存先を選ぶ','Choose Save as PDF, then a destination'),
 (63,68,'保存完了。PDFはダークモードでも白い紙面','PDF saved. PDF pages stay white, even in dark mode.'),
 (68,70,'編集画面に戻る','Return to the document'),
 (70,75,'mdEditor · Microsoft Storeで無料 / 5garashi.com','mdEditor · Free on Microsoft Store / 5garashi.com')]
def stamp(n,ass=False):return f'0:{n//60:02}:{n%60:02}.00' if ass else f'00:{n//60:02}:{n%60:02}.000'
results=[]
for lang in ('en','ja'):
    ass='''[Script Info]
ScriptType: v4.00+
PlayResX: 1280
PlayResY: 720
WrapStyle: 2
[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Default,Meiryo,24,&H00235738,&H00235738,&H00CBEFF9,&H00CBEFF9,-1,0,0,0,100,100,0,0,1,0,0,2,32,32,24,1
[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
'''
    vtt=f'WEBVTT\n\nNOTE\nFile: demo-{lang}.vtt\nDescription: Extended Windows demonstration captions\nAuthor: 5garashi.com Design Office\nCreated: 2026-10-14\nVersion: 1.1.0\nLicense: MIT\nSPDX-License-Identifier: MIT\n\n'
    for a,b,ja,en in CAPTIONS:
        t=en if lang=='en' else ja
        ass+=f'Dialogue: 0,{stamp(a,True)},{stamp(b,True)},Default,,0,0,0,,{t}\n'
        vtt+=f'{stamp(a)} --> {stamp(b)}\n{t}\n\n'
    (WORK/f'captions-{lang}.ass').write_text(ass,encoding='utf-8-sig')
    (ASSETS/f'demo-{lang}.vtt').write_text(vtt,encoding='utf-8')
    output=ASSETS/f'mdEditor-demo-{lang}.mp4'
    # Take the first 20 complete 5/4 bars (48s), repeat, then fade at the ending.
    # Original WAV is retained. Caption ink/paper contrast is 7.14:1.
    filters=f'[0:v]pad=1280:720:8:0:color=0xF9EFCB,ass=captions-{lang}.ass[v];[1:a]atrim=0:48,asetpts=PTS-STARTPTS,aloop=loop=1:size=2116800,atrim=0:75,afade=t=in:st=0:d=0.15,afade=t=out:st=73.5:d=1.5[a]'
    subprocess.run(['ffmpeg','-y','-i',str(WORK/f'raw-{lang}.mp4'),'-i',str(MUSIC),'-filter_complex',filters,'-map','[v]','-map','[a]','-t','75','-r','20','-c:v','libx264','-preset','medium','-crf','20','-pix_fmt','yuv420p','-c:a','aac','-b:a','192k','-movflags','+faststart','-metadata','title=mdEditor Demo — separate preview, dark mode, Syntax and PDF','-metadata','artist=5garashi.com Design Office','-metadata','copyright=Original Light Steps music generated by Codex for 5garashi.com Design Office; music license not specified; captions MIT; official logo CC BY-ND 4.0','-metadata','comment=Unmodified Windows source build 1.0.5; real operations; 125 BPM 5/4 Light Steps excerpt repeated to fit',str(output)],cwd=WORK,check=True,stdout=subprocess.DEVNULL,stderr=(WORK/f'encode-{lang}.log').open('w'))
    subprocess.run(['ffmpeg','-y','-v','error','-ss','42','-i',str(output),'-frames:v','1',str(ASSETS/f'video-poster-{lang}.png')],check=True)
    data=json.loads(subprocess.check_output(['ffprobe','-v','error','-show_entries','format=duration:stream=codec_type,width,height,sample_rate,channels','-of','json',str(output)]))
    assert float(data['format']['duration'])==75
    assert any(s['codec_type']=='audio' and s['channels']==2 for s in data['streams'])
    results.append({'file':output.name,'capture':json.loads((WORK/f'recording-{lang}.json').read_text(encoding='utf-8')),'encoding':data})
    print('Encoded extended demo:',lang,flush=True)
(ROOT/'validation/media-v2-results.json').write_text(json.dumps({'date':'2026-10-14 JST','demo_revision':'1.1.0','music':'Light Steps v1 — 125 BPM, 5/4, 20-bar excerpt repeated','results':results},ensure_ascii=False,indent=2),encoding='utf-8')
